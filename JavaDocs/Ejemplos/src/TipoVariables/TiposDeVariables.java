package TipoVariables;

public class TiposDeVariables {

	public static void main(String[] args) {
		
		
		byte edadAlumno; //Declaramos la variable edadAlumno
		edadAlumno = 17; //Inicializamos la variable edadAlumno
		System.out.println("La edad del alumno es: " + edadAlumno);
		
		short cantidadAlumnos;
		cantidadAlumnos = 2157;
		System.out.println("El numero de alumnos en el centro es de: " + cantidadAlumnos);
		
		int habitantesTorremolinos;
		habitantesTorremolinos = 73567;
		System.out.println("En Torremolinos habitan: " + habitantesTorremolinos);
		
		long habitantesEspaña;
		habitantesEspaña = 823468733;
		System.out.println("En España habitan: " + habitantesEspaña);
		
		char numeroChar;
		numeroChar = 'h';
		System.out.println("La letra es: " + numeroChar);
		
		float numeroFloat;
		numeroFloat = 567;
		System.out.println("A la tarta hay que echarle de harina: " + numeroFloat + "gr");
		
		double numeroDouble;
		numeroDouble = 218923833;
		System.out.println("No se que numero es: " + numeroDouble );

	}

}
